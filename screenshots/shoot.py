from playwright.sync_api import sync_playwright
U="http://127.0.0.1:4322/"; D="/workspace/sites/gta6-community/screenshots/"
with sync_playwright() as p:
    b=p.chromium.launch(executable_path="/usr/bin/google-chrome")
    errs=[]
    pg=b.new_page(viewport={"width":1440,"height":900})
    pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: m.type=="error" and errs.append(m.text))
    pg.goto(U, wait_until="networkidle"); pg.wait_for_timeout(600)
    pg.evaluate("document.querySelectorAll('img[loading=lazy]').forEach(i=>i.loading='eager')"); pg.wait_for_load_state("networkidle"); pg.wait_for_timeout(400)
    pg.screenshot(path=D+"01-desktop-hero.png")
    pg.screenshot(path=D+"02-desktop-fullpage.png", full_page=True)
    pg.click('button[aria-controls="dd-explore"]'); pg.wait_for_timeout(200)
    pg.screenshot(path=D+"03-desktop-dropdown.png", clip={"x":0,"y":0,"width":1440,"height":400})
    m=b.new_page(viewport={"width":390,"height":844}, device_scale_factor=2, is_mobile=True, has_touch=True)
    m.on("pageerror", lambda e: errs.append(str(e)))
    m.goto(U, wait_until="networkidle"); m.wait_for_timeout(600)
    m.evaluate("document.querySelectorAll('img[loading=lazy]').forEach(i=>i.loading='eager')"); m.wait_for_load_state("networkidle"); m.wait_for_timeout(400)
    m.screenshot(path=D+"04-mobile-hero.png")
    m.click(".burger"); m.wait_for_timeout(300)
    m.screenshot(path=D+"05-mobile-menu-open.png")
    m.click(".burger"); m.wait_for_timeout(400)
    m.screenshot(path=D+"06-mobile-fullpage.png", full_page=True)
    print("mobile scrollWidth", m.evaluate("document.documentElement.scrollWidth"), "errors", errs)
    pg.keyboard.press("Escape"); pg.mouse.click(5,600); pg.wait_for_timeout(200); pg.evaluate("window.scrollTo(0,0)"); pg.add_style_tag(content=".hdr{position:relative!important}")
    pg.locator(".hero__right").screenshot(path=D+"07-map-section.png")
    pg.locator("#regions").screenshot(path=D+"08-regions-grid.png")
    y0,y1=pg.evaluate("[document.querySelector('.hero__right').getBoundingClientRect().top+scrollY-16, document.querySelector('#regions').getBoundingClientRect().bottom+scrollY]")
    print("dropdown open:", pg.is_visible("#dd-explore"))
    pg.screenshot(path=D+"09-map-and-regions.png", full_page=True, clip={"x":0,"y":y0,"width":1440,"height":y1-y0})
    print("broken imgs", pg.evaluate("[...document.images].filter(i=>i.naturalWidth===0).map(i=>i.src)"))
    b.close()
